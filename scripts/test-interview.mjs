#!/usr/bin/env node
/**
 * Phase 1 Integration Test
 * ─────────────────────────
 * POSTs a start message, then 8 follow-up messages, then asserts:
 *   - Every mid-turn response has { reply: string, done: false }
 *   - The final (9th candidate message) response has:
 *       done: true
 *       feedback.summary (string)
 *       feedback.strengths (non-empty array)
 *       feedback.gaps     (non-empty array)
 *       feedback.next     (non-empty array)
 *
 * Usage:
 *   node scripts/test-interview.mjs
 *   # or with a custom base URL:
 *   BASE_URL=http://localhost:4000 node scripts/test-interview.mjs
 */

const BASE_URL = process.env.BASE_URL ?? 'http://localhost:3000';
const ENDPOINT = `${BASE_URL}/api/interview`;
const SESSION_ID = `test-session-${Date.now()}`;

// ─── Sample candidate (CAND-001 from candidates.json) ─────────────────────────
const CANDIDATE = {
  member: {
    id: 'CAND-001',
    name: 'Sarah Johnson',
    jobRole: 'Senior Data Engineer',
    yearsExperience: 9,
    education: 'MS Computer Science',
    status: 'COMPLETED',
  },
  missions: [
    { day: 7,  title: 'Embeddings Explained',              passed: true, attempts: 1 },
    { day: 8,  title: 'Vector Databases Overview',         passed: true, attempts: 1 },
    { day: 10, title: 'Retrieval & Matching Engine',       passed: true, attempts: 2 },
    { day: 12, title: 'Prompt Engineering Fundamentals',   passed: true, attempts: 4 },
    { day: 16, title: 'Chatbot Backend & API Integration', passed: true, attempts: 1 },
    { day: 22, title: 'Multi-Agent Orchestration',         passed: true, attempts: 2 },
    { day: 23, title: 'Model Context Protocol (MCP)',      passed: true, attempts: 2 },
    { day: 28, title: 'Docker & Kubernetes Deployment',    passed: true, attempts: 3 },
    { day: 29, title: 'Monitoring, Logging & Observability', skipped: true },
    { day: 31, title: 'Capstone Project & Final Demo',     passed: true, attempts: 1 },
  ],
  signals: { commitDays: 28, missionsCompleted: 30, missionsFirstTry: 20 },
};

// ─── Utilities ────────────────────────────────────────────────────────────────

let passed = 0;
let failed = 0;

function assert(condition, message) {
  if (condition) {
    console.log(`  ✅  ${message}`);
    passed++;
  } else {
    console.error(`  ❌  FAIL: ${message}`);
    failed++;
  }
}

async function post(body) {
  const res = await fetch(ENDPOINT, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(body),
  });
  const json = await res.json();
  return { status: res.status, json };
}

// ─── Test runner ──────────────────────────────────────────────────────────────

async function run() {
  console.log(`\n🧪  Phase 1 Integration Test`);
  console.log(`    Endpoint  : ${ENDPOINT}`);
  console.log(`    SessionId : ${SESSION_ID}`);
  console.log(`    Candidate : ${CANDIDATE.member.name}\n`);

  // ── 1. Start turn ────────────────────────────────────────────────────────
  console.log('─── Turn 0 (start) ───');
  const { status: s0, json: r0 } = await post({ sessionId: SESSION_ID, candidate: CANDIDATE });

  assert(s0 === 200,         `HTTP 200 on start (got ${s0})`);
  assert(typeof r0.reply === 'string' && r0.reply.length > 0, 'reply is a non-empty string');
  assert(r0.done === false,  'done is false');
  assert(!('feedback' in r0),'no feedback key on opening turn');
  console.log(`    reply preview: "${r0.reply.slice(0, 80)}…"\n`);

  // ── 2. Mid turns (8 candidate messages) ────────────────────────────────
  const CANDIDATE_REPLIES = [
    'Embeddings are dense vector representations of text, generated by transformer models.',
    'I would choose ChromaDB for local development and Pinecone for production scale.',
    'RAG connects retrieval output to the LLM prompt. Bottlenecks are usually retrieval latency.',
    'The hardest part of prompt engineering was reducing hallucinations in edge cases.',
    'ReAct agents use a thought-action-observation loop to select tools iteratively.',
    'MCP standardises how context is passed between tools and models across providers.',
    'I used a sliding window for conversation memory with summarisation for older turns.',
    'I would prioritise input validation and prompt injection guardrails first.',
  ];

  let finalResponse = null;

  for (let i = 0; i < CANDIDATE_REPLIES.length; i++) {
    const turnNum = i + 1;
    const isLast = i === CANDIDATE_REPLIES.length - 1;
    console.log(`─── Turn ${turnNum} (mid${isLast ? ' — expect done:true' : ''}) ───`);

    const { status, json } = await post({
      sessionId: SESSION_ID,
      message: CANDIDATE_REPLIES[i],
    });

    assert(status === 200, `HTTP 200 on turn ${turnNum} (got ${status})`);
    assert(typeof json.reply === 'string' && json.reply.length > 0, `reply is a non-empty string`);

    if (isLast) {
      assert(json.done === true, 'done is true on final turn');
      finalResponse = json;
    } else {
      assert(json.done === false, `done is false on turn ${turnNum}`);
      assert(!('feedback' in json), `no feedback on mid turn ${turnNum}`);
    }

    console.log(`    reply preview: "${(json.reply ?? '(no reply — error response)').slice(0, 80)}…"\n`);

  }

  // ── 3. Feedback shape assertions ────────────────────────────────────────
  console.log('─── Feedback assertions ───');
  assert(finalResponse !== null, 'received a final response');

  if (finalResponse) {
    const fb = finalResponse.feedback;
    assert(typeof fb === 'object' && fb !== null,           'feedback is an object');
    assert(typeof fb.summary === 'string' && fb.summary.length > 0, 'feedback.summary is a non-empty string');
    assert(Array.isArray(fb.strengths) && fb.strengths.length > 0,  'feedback.strengths is a non-empty array');
    assert(Array.isArray(fb.gaps)      && fb.gaps.length > 0,       'feedback.gaps is a non-empty array');
    assert(Array.isArray(fb.next)      && fb.next.length > 0,       'feedback.next is a non-empty array');

    // Each array item must be a string
    assert(fb.strengths.every(s => typeof s === 'string'), 'every strengths item is a string');
    assert(fb.gaps.every(s      => typeof s === 'string'), 'every gaps item is a string');
    assert(fb.next.every(s      => typeof s === 'string'), 'every next item is a string');

    console.log('\n    Feedback preview:');
    console.log(`    summary   : "${fb.summary.slice(0, 100)}…"`);
    console.log(`    strengths : [${fb.strengths.length} item(s)]`);
    console.log(`    gaps      : [${fb.gaps.length} item(s)]`);
    console.log(`    next      : [${fb.next.length} item(s)]`);
  }

  // ── 4. Error-case: unknown sessionId ─────────────────────────────────
  console.log('\n─── Error-case: unknown sessionId ───');
  const { status: s404 } = await post({ sessionId: 'nonexistent-session-xyz', message: 'hello' });
  assert(s404 === 404, `unknown sessionId returns HTTP 404 (got ${s404})`);

  // ── 5. Error-case: malformed candidate ────────────────────────────────
  console.log('\n─── Error-case: malformed candidate ───');
  const { status: s400 } = await post({ sessionId: `bad-session-${Date.now()}`, candidate: { bad: 'data' } });
  assert(s400 === 400, `malformed candidate returns HTTP 400 (got ${s400})`);

  // ── 6. Error-case: missing sessionId ─────────────────────────────────
  console.log('\n─── Error-case: missing sessionId ───');
  const { status: sNoId } = await post({ message: 'hello' });
  assert(sNoId === 400, `missing sessionId returns HTTP 400 (got ${sNoId})`);

  // ── Summary ────────────────────────────────────────────────────────────
  console.log('\n══════════════════════════════════════');
  console.log(`  Results: ${passed} passed, ${failed} failed`);
  console.log('══════════════════════════════════════\n');

  if (failed > 0) {
    process.exit(1);
  }
}

run().catch((err) => {
  console.error('\n💥  Unexpected error:', err.message);
  process.exit(1);
});
